FALLBACK = {'$': 'S', '@': 'O', '\\': '/', '^': "'", '`': "'", '{': '(', '}': ')', '~': '-'}

EXTRA_ORDER = ['★', '◆']
EXTRA = {
    '★': ['.....#.....', '....###....', '....###....', '###########', '.#########.', '..#######..',
          '...#####...', '..###.###..', '..##...##..', '.##.....##.', '.#.......#.'],
    '◆': ['....#....', '...###...', '..#####..', '.#######.', '#########', '.#######.', '..#####..',
          '...###...', '....#....'],
}


def gradient_color(y):
    if y <= 2:
        return 4
    if y <= 4:
        return 5
    if y <= 7:
        return 3
    return 2


def glyph(rows):
    cell = Canvas(16, 16)
    width = max(len(r) for r in rows)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#':
                cell.set(1 + x, 2 + y, gradient_color(y))
    cell.outline(1, diagonal=True)
    return cell, width


def build():
    chars = [chr(c) for c in range(33, 127)]
    sheet = Canvas(16, 16 * (len(chars) + len(EXTRA_ORDER)))
    widths = [8]
    for i, ch in enumerate(chars):
        key = ch.upper() if 'a' <= ch <= 'z' else ch
        rows = BIG.get(key) or BIG[FALLBACK[key]]
        cell, w = glyph(rows)
        sheet.blit(cell, 0, i * 16)
        widths.append(w + 2)
    for j, ch in enumerate(EXTRA_ORDER):
        cell, w = glyph(EXTRA[ch])
        sheet.blit(cell, 0, (len(chars) + j) * 16)
        widths.append(w + 2)
    return sheet, widths


def title_palette(outline, dark, mid, light, highlight):
    return [P.TRANSPARENT, outline, dark, mid, light, highlight] + [(0, 0, 0)] * 10


TITLE_PALETTES = {
    'title_gold': title_palette((44, 20, 8), (150, 88, 24), (214, 152, 52), (250, 214, 110), (255, 250, 214)),
    'title_silver': title_palette((18, 16, 40), (110, 116, 150), (170, 178, 206), (226, 232, 246), (255, 255, 255)),
    'title_ruby': title_palette((36, 6, 12), (140, 22, 40), (210, 52, 70), (250, 130, 130), (255, 220, 210)),
    'title_arcane': title_palette((10, 14, 40), (60, 80, 180), (100, 160, 240), (170, 230, 255), (240, 255, 255)),
    'title_dim': title_palette((16, 12, 28), (60, 56, 84), (90, 86, 116), (120, 116, 146), (150, 146, 176)),
}


def generate(root):
    graphics = os.path.join(root, 'graphics')
    include = os.path.join(root, 'include')
    sheet, widths = build()
    write_bmp(os.path.join(graphics, 'font_big.bmp'), sheet, TITLE_PALETTES['title_gold'], bpp=4)
    write_json(os.path.join(graphics, 'font_big.json'), {'type': 'sprite', 'height': 16})
    write_header(os.path.join(include, 'cl_font_big.h'), 'big', 'font_big', widths, EXTRA_ORDER, 16)
    write_metrics(os.path.join(root, 'core', 'cl_metrics_big.h'), 'big', widths, EXTRA_ORDER)
    swatch = Canvas(8, 8)
    for i in range(16):
        swatch.set(i % 8, i // 8, i)
    for name, pal in TITLE_PALETTES.items():
        write_bmp(os.path.join(graphics, name + '.bmp'), swatch, pal, bpp=4)
        write_json(os.path.join(graphics, name + '.json'), {'type': 'sprite_palette'})

    chars = [chr(c) for c in range(33, 127)]
    preview = Canvas(240, 56)
    y = 1
    for line in ('STORY MODE', 'Arcane Chess 2048', 'CHECKMATE! WHO? ★'):
        x = 2
        for ch in line:
            if ch == ' ':
                x += widths[0]
                continue
            if ch in EXTRA_ORDER:
                index = len(chars) + EXTRA_ORDER.index(ch)
            else:
                index = chars.index(ch)
            preview.blit(sheet.crop(0, index * 16, 16, 16), x, y)
            x += widths[index + 1]
        y += 18
    pal = list(TITLE_PALETTES['title_gold'])
    pal[0] = (38, 36, 72)
    write_png(os.path.join(root, 'assets_source', 'previews', 'font_big.png'), preview, pal, scale=3,
              transparent_color=None)


if __name__ == '__main__':
    generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
